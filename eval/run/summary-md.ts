// Renders the Results block of docs/EVAL.md from committed artefacts only (never hand-typed numbers):
//   node eval/run/summary-md.ts --out runs/eval-2026-09-28-v2 --ft runs/ft-kev-0.8b-2026-09-28 [--ft4b runs/ft-kev-4b-2026-09-29] > block.md
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const arg = (k: string) => { const i = process.argv.indexOf(`--${k}`); return i > 0 ? process.argv[i + 1] : undefined; };
const out = arg('out')!, ft = arg('ft')!, ft4b = arg('ft4b');
const summary = JSON.parse(readFileSync(join(out, 'summary.json'), 'utf8')) as Record<string, Record<string, Record<string, number | null | number[]>>>;
const items = readFileSync('eval/splits/items.jsonl', 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l) as { split: string });
const bySplit = items.reduce<Record<string, number>>((a, i) => { a[i.split] = (a[i.split] ?? 0) + 1; return a; }, {});
const f = (v: unknown, d = 3) => (typeof v === 'number' ? v.toFixed(d) : '—');
const ms = (v: unknown) => (typeof v === 'number' ? `${Math.round(v)} ms` : '—');

/** One fine-tune record (RUN.txt, train.log, Kev's training_config.json) as the paragraph the block shows. */
function fineTune(dir: string, name: string): string {
  const run = readFileSync(join(dir, 'RUN.txt'), 'utf8');
  const log = readFileSync(join(dir, 'train.log'), 'latin1').replace(/\r/g, '\n');
  const cfg = JSON.parse(readFileSync(join(dir, 'training_config.json'), 'utf8')) as { init_source?: { init_from?: string; weights_sha256?: string } };
  // Hyperparameters are not in Kev's training_config.json; they come from the committed launcher.
  const launcher = readFileSync('eval/finetune/finetune.sh', 'utf8');
  const epochs = /--epochs (\S+)/.exec(run)?.[1] ?? /--epochs (\S+)/.exec(launcher)?.[1];
  const lr = /--lr (\S+)/.exec(run)?.[1] ?? /--lr (\S+)/.exec(launcher)?.[1];
  const fileRecords = Number(/records=\s*(\d+)/.exec(run)?.[1]);
  const used = Number(/(\d+) training requests/.exec(log)?.[1]);
  const dropped = /dropped (\d+) of (\d+) records/.exec(log);
  const wall = Number(/wall_s=(\d+)/.exec(run)?.[1]);
  const host = /host=(.+?) memory_gb=(\d+)/.exec(run);
  return `**Fine-tune (B2-ft), ${name}:** LoRA, \`--init_from ${cfg.init_source?.init_from ?? '?'}\` (weights sha256 ${cfg.init_source?.weights_sha256?.slice(0, 12) ?? '?'}…), ${epochs} epochs, lr ${lr} (from eval/finetune/finetune.sh), on ${fileRecords} train records of which Kev used ${used} (${dropped ? `${dropped[1]} dropped as longer than its 384-token training context` : 'none dropped'}); wall time ${Math.round(wall / 60)} min on MPS${host ? ` (${host[1]}, ${host[2]} GB)` : ''}; ${/result=(\S+)/.exec(run)?.[1] ?? '?'} inside the 3 h box.`;
}
const MODELS = [['kev-0.8b', 'Kev-0.8B'], ['kev-4b', 'Kev-4B'], ['kev-0.8b-ft', 'Kev-0.8B fine-tuned'], ['kev-4b-ft', 'Kev-4B fine-tuned']] as const;
const heldOut = (label: string, key: string) => summary[label]?.[key] ?? {};

const L: string[] = [];
L.push(`<!-- generated by eval/run/summary-md.ts from ${out}, ${ft}${ft4b ? ` and ${ft4b}` : ''}; do not edit by hand -->`);
L.push(`Held-out items: calibration ${bySplit.calibration ?? 0}, dev ${bySplit.dev ?? 0}, test ${bySplit.test ?? 0} (test = AgentDojo, never seen in training).`, '');
L.push(fineTune(ft, 'Kev-0.8B'), '');
if (ft4b) L.push(fineTune(ft4b, 'Kev-4B'), '');
L.push(`**Held-out family (AgentDojo test).**`, '');
L.push(`| model | instruction_override AUROC | goal_deviation AUROC | goal_deviation recall @ calibration threshold [95% CI] · FPR |`);
L.push(`|---|---|---|---|`);
const io0 = heldOut(Object.keys(summary)[0], 'instruction_override/test');
L.push(`| B0 heuristics | acc ${f(io0.b0_acc)}, recall ${f(io0.b0_recall)} | no code baseline | — |`);
for (const [label, name] of MODELS) {
  if (!summary[label]) continue;
  const io = heldOut(label, 'instruction_override/test'), gd = heldOut(label, 'goal_deviation/test');
  const ci = Array.isArray(gd.recall_thr_ci) ? ` [${f(gd.recall_thr_ci[0])}, ${f(gd.recall_thr_ci[1])}]` : '';
  L.push(`| ${name} | ${f(io.auroc)} | ${f(gd.auroc)} | ${f(gd.recall_thr)}${ci} · ${f(gd.fpr_thr)} |`);
}
L.push('', `**Judge HTTP round trip on this machine** (from each prediction file):`, '');
L.push(`| model | p50 | p95 | n |`, `|---|---|---|---|`);
for (const [label, name] of MODELS) {
  const m = summary[label]?._meta as unknown as { rtt_p50_ms: number; rtt_p95_ms: number; rtt_n: number } | undefined;
  if (m) L.push(`| ${name} | ${ms(m.rtt_p50_ms)} | ${ms(m.rtt_p95_ms)} | ${m.rtt_n} |`);
}
L.push('', `<!-- /generated -->`);
console.log(L.join('\n'));
