// docs/GATE.md's measured table must equal what scripts/gate-summary.ts renders from the recorded runs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
test('GATE.md generated table matches the recorded gate runs', { skip: !existsSync('runs/gate-smoke-2026-09-28') ? 'no recorded gate runs' : false }, () => {
  const block = execFileSync('node', ['scripts/gate-summary.ts', 'runs/gate-smoke-2026-09-28'], { encoding: 'utf8' }).trim();
  const doc = readFileSync('docs/GATE.md', 'utf8');
  const a = doc.indexOf('<!-- generated by scripts/gate-summary.ts'), b = doc.indexOf('<!-- /generated -->');
  assert.ok(a >= 0 && b > a);
  assert.equal(doc.slice(a, b + '<!-- /generated -->'.length).trim(), block);
});
