// docs/EVAL.md's Results numbers must be exactly what eval/run/summary-md.ts computes from the committed artefacts.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';

test('EVAL.md generated block matches the committed predictions and fine-tune record', { skip: !existsSync('runs/eval-2026-09-28-v2/summary.json') ? 'no eval run committed' : false }, () => {
  const block = execFileSync('node', ['eval/run/summary-md.ts', '--out', 'runs/eval-2026-09-28-v2', '--ft', 'runs/ft-kev-0.8b-2026-09-28', '--ft4b', 'runs/ft-kev-4b-2026-09-29'], { encoding: 'utf8' }).trim();
  const doc = readFileSync('docs/EVAL.md', 'utf8');
  const start = doc.indexOf('<!-- generated by eval/run/summary-md.ts'), end = doc.indexOf('<!-- /generated -->');
  assert.ok(start >= 0 && end > start, 'generated block markers missing');
  assert.equal(doc.slice(start, end + '<!-- /generated -->'.length).trim(), block);
});
